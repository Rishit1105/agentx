"""Hindi and Hinglish voice: commands in, Devanagari replies out.

Indian traders mix languages: "Zomato mein trade plan karo", "haan, 482 ETERNAL khareedo", "sab band karo". Instead of a
second grammar, this module normalises Hindi / Hinglish (romanised or Devanagari) into the English commands the
deterministic grammar already understands, so the safety rules stay identical in both languages:

  * halt words ("sab band karo", "trading roko", "रुको", "बंद करो") always become "stop everything";
  * a confirmation must still start with yes ("haan" / "हाँ") and name the exact quantity and symbol;
  * nothing here ever creates an order on its own.

Replies are localised by matching the Conductor's own English templates (they are generated by code, so they are
predictable); numbers, tickers and prices are kept as they are. Anything without a template stays in English.
"""
from __future__ import annotations

import re

DEVANAGARI = re.compile(r"[ऀ-ॿ]")

# Devanagari words -> romanised Hinglish (so one set of patterns handles both scripts)
DEVA = {
    "हाँ": "haan", "हां": "haan", "हा": "haan", "नहीं": "nahi", "नही": "nahi", "खरीदो": "khareedo", "ख़रीदो": "khareedo",
    "खरीदें": "khareedo", "बेचो": "becho", "बंद": "band", "करो": "karo", "रुको": "ruko", "रोको": "roko", "सब": "sab",
    "स्कैन": "scan", "ब्रेकआउट": "breakout", "प्लान": "plan", "ट्रेड": "trade", "में": "mein", "का": "ka", "की": "ki",
    "शेयर": "share", "बाज़ार": "bazaar", "बाजार": "bazaar", "कैसा": "kaisa", "है": "hai", "सुप्रभात": "suprabhat",
    "नमस्ते": "namaste", "मेरा": "mera", "पैसा": "paisa", "मुनाफ़ा": "munafa", "नुकसान": "nuksaan", "स्टॉप": "stop",
    "ब्रेकईवन": "breakeven", "अगर": "agar", "तो": "to", "क्या": "kya", "सेक्टर": "sector", "मूड": "mood",
    "शांत": "shant", "घबराहट": "ghabrahat", "बदला": "badla", "टिल्ट": "tilt", "मीरिडियन": "meridian",
}
NUMS = {"ek": 1, "do": 2, "teen": 3, "char": 4, "chaar": 4, "paanch": 5, "panch": 5, "das": 10, "sau": 100,
        "hazaar": 1000, "hazar": 1000}

HINGLISH_MARKERS = re.compile(
    r"\b(karo|kar do|kijiye|dikhao|batao|khareedo|kharido|becho|band|roko|ruko|mein|haan|nahi|kaisa|kitna|mera|"
    r"suprabhat|namaste|dhoondo|lagao|le jao|agar|bazaar|munafa|nuksaan|sab|chahiye|hoon|hun|bhai|kaise|kaisi|hain)\b")


def is_hindi(text: str) -> bool:
    return bool(DEVANAGARI.search(text)) or bool(HINGLISH_MARKERS.search(text.lower()))


def _romanise(text: str) -> str:
    out = text
    for k, v in sorted(DEVA.items(), key=lambda kv: -len(kv[0])):
        out = out.replace(k, f" {v} ")
    return re.sub(r"\s+", " ", out).strip()


def to_english(raw: str) -> tuple[str, bool]:
    """(English command, was it Hindi/Hinglish). Unrecognised Hindi passes through romanised."""
    if not is_hindi(raw):
        return raw, False
    t = _romanise(raw).lower().strip(" .!?।")
    t = re.sub(r"^(hey|hi|ok|okay)?\s*,?\s*(meridian)\s*,?\s*", "", t)
    # safety first: halt words in Hindi
    if re.search(r"\b(sab|sabhi|saari|saara)\s+(band|ruko|roko|rok do|band karo|khatam)\b|\btrading\s+(band|roko|rok do)\b|"
                 r"^(ruko|roko|band karo|rok do)\b|\bemergency\b", t):
        return "stop everything", True
    # yes / no for a pending ticket: "haan, 482 ETERNAL khareedo" -> "yes, buy 482 ETERNAL"
    m = re.match(r"^(haan|haa|ha|ji haan|ji)\b[\s,]*(?:(\d+)\s+([a-z0-9&-]+)|([a-z0-9&-]+)\s+(?:ke\s+|ka\s+)?(\d+))"
                 r"(?:\s+(?:share|shares))?\s*(?:khareedo|kharido|le lo|lo|buy|kharid lo)?\s*$", t)
    if m:
        qty, sym = (m.group(2), m.group(3)) if m.group(2) else (m.group(5), m.group(4))
        return f"yes, buy {qty} {sym.upper()}", True
    if re.match(r"^(haan|haa|ji haan)\b", t):
        return "yes", True                       # a bare yes is still rejected by the confirm rules
    if re.match(r"^(nahi|nahin|mat karo|rehne do|cancel)\b", t):
        return "no", True
    if re.search(r"\b(suprabhat|namaste|good morning)\b|\bbazaar\s+(kaisa|ka haal)\b|\bmarket\s+kaisa\b", t):
        return "good morning", True
    if re.search(r"\b(sector|sectors)\b", t):
        return "how are sectors doing", True
    if re.search(r"\b(scan|breakout|breakouts)\b", t) and re.search(r"\b(karo|kar do|dikhao|dhoondo|batao|chahiye)\b|scan", t):
        return "scan for breakouts", True
    m = re.search(r"\bagar\s+(?:main\s+|mai\s+|me\s+)?(\d+)\s+([a-z0-9&-]+)\s+(?:share\s+)?(?:khareedu|kharidu|loon|lun|kharidoon)", t)
    if m:
        return f"what if I buy {m.group(1)} {m.group(2)}", True
    if re.search(r"\bstop\b.*\b(breakeven|entry|cost)\b", t):
        return "move my stop to breakeven", True
    m = re.search(r"\b([a-z0-9&-]+)\s+(?:mein|me|ka|ki|par|pe)\s+(?:ek\s+)?trade\s+(?:plan|set ?up|bana)", t) or \
        re.search(r"\btrade\s+(?:plan|bana)\w*\s+(?:karo|kar do)?\s*([a-z0-9&-]+)\s+(?:mein|me|ka|par)\b", t)
    if m:
        return f"plan a trade on {m.group(1)}", True
    m = re.search(r"\b([a-z0-9&-]+)\s+(?:ka|ki)\s+(?:news|khabar)", t)
    if m:
        return f"what's moving {m.group(1)}", True
    if re.search(r"\b(mera|hamara)?\s*(p ?& ?l|pnl|munafa|nuksaan|paisa|balance)\b.*\b(kya|kitna|batao|dikhao)\b|\bkitna\s+(kamaya|gaya)\b", t):
        return "how am I doing", True
    if re.search(r"\b(limit|limits|guardrail|guardrails|niyam)\b", t):
        return "what are my guardrails", True
    if re.search(r"\btilt\b|\bbadla\b.*\b(le raha|trading)\b", t):
        return "am I on tilt", True
    m = re.search(r"\b(?:main|mai|mood)\b.*\b(shant|calm|ghabrahat|nervous|fomo|badla|revenge)\b", t)
    if m:
        word = {"shant": "calm", "ghabrahat": "anxious", "nervous": "anxious", "badla": "revenge"}.get(m.group(1), m.group(1))
        conf = re.search(r"\b(\d)\b", t)
        return f"I'm feeling {word}" + (f", confidence {conf.group(1)}" if conf else ""), True
    if re.search(r"\b(compliance|sebi)\b", t):
        return "compliance report", True
    return t, True


