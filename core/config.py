def ensure_config() -> dict:
    if not CONFIG_PATH.exists():
        shutil.copy(DEFAULT_CONFIG, CONFIG_PATH)
    cfg = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    changed = False
    for k, v in MERIDIAN_DEFAULTS.items():
        if k not in cfg:
            cfg[k] = v
            changed = True
    if cfg.get("sec_user_agent", "").startswith("Your Name"):
        cfg["sec_user_agent"] = ENV["sec_user_agent"]
        changed = True
    if changed:
        write_config(cfg)
    return cfg


def read_config() -> dict:
    return json.loads(CONFIG_PATH.read_text(encoding="utf-8"))


def write_config(cfg: dict) -> None:
    tmp = CONFIG_PATH.with_suffix(".tmp")
    tmp.write_text(json.dumps(cfg, indent=2), encoding="utf-8")
    os.replace(tmp, CONFIG_PATH)


LIVE_KEY_PATTERNS = [re.compile(r"^AK[A-Z0-9]{16,}$")]  # Alpaca live keys start AK; paper keys PK


class PaperAssertionError(RuntimeError):
    pass


def paper_assertion(cfg: dict) -> dict:
    """L0: refuse to run unless every real-money path is impossible."""
    problems = []
    if cfg.get("paper") is not True:
        problems.append("config.paper must be true")
    if cfg.get("broker", "paper") not in ("paper", "alpaca"):
        problems.append("config.broker must be the paper broker")
    if cfg.get("meridian_broker", "mock") not in ("mock", "alpaca_paper"):
        problems.append("meridian_broker must be mock or alpaca_paper")
    if ENV["broker"] not in ("mock", "alpaca_paper"):
        problems.append("MERIDIAN_BROKER must be mock or alpaca_paper")
    if not ENV["alpaca_paper_url"].startswith("https://paper-api.alpaca.markets"):
        problems.append("Alpaca base URL must be paper-api.alpaca.markets")
    for k, v in os.environ.items():
        if "ALPACA" in k.upper() and "KEY" in k.upper():
            if any(p.match(v or "") for p in LIVE_KEY_PATTERNS):
                problems.append(f"{k} looks like a live key")
    if os.getenv("ALPACA_PAPER_TRADE", "true").lower() != "true":
        problems.append("ALPACA_PAPER_TRADE must be true")
    if problems:
        raise PaperAssertionError("; ".join(problems))
    return {"ok": True, "broker": cfg.get("meridian_broker", "mock"), "paper": True}
